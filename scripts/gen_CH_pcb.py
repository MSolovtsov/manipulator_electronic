# Земли: внутри своей зоны площадки соединяет заливка (зона GND_L — B.Cu слева от ISO_X1, GND_P — F.Cu правее ISO_X2),
# дорожками ведутся только площадки вне своей зоны плюс одна точка привязки внутри неё — иначе Router тянет землю
# через всю плату с десятком переходов (блок 11 check_pcb.py). Зоны объявлены ниже; границы — те же константы.
ISO_X1, ISO_X2 = 46.0, 50.0                       # полоса между зонами (медь зон туда не заливается)
def ground_pads(net):
    inside = (lambda p: p[0] < ISO_X1) if net == "GND_L" else (lambda p: p[0] > ISO_X2)
    pts = pads_of(net)
    out = [p for p in pts if not inside(p)]
    anchor = [p for p in pts if inside(p)]
    if out and anchor:
        out.append(min(anchor, key=lambda a: min(math.hypot(a[0] - q[0], a[1] - q[1]) for q in out)))
    return out if len(out) > 1 else []

for net, w in ORDER:
    pts = sorted(ground_pads(net) if net in ("GND_L", "GND_P") else pads_of(net), key=lambda p: (p[1], p[0]))
    if not pts:
        continue
    chain = [pts[0]]; rest = pts[1:]
    while rest:
        nxt = min(rest, key=lambda p: min(math.hypot(p[0] - q[0], p[1] - q[1]) for q in chain))
        chain.append(nxt); rest.remove(nxt)
    rt.route(net, chain, w)
