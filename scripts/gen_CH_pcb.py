for _i in range(4):
    _f.tht(str(_i + 1), -3.81, -3.81 + _i * 2.54, 0.8, 1.6, "rect" if _i == 0 else "circle")
    _f.tht(str(8 - _i), 3.81, -3.81 + _i * 2.54, 0.8, 1.6)
_f.outline(-3.3, -5.3, 3.3, 5.3)
_f.text("F.SilkS", "1", -5.9, -3.81, 1.0)
