    ro = (3.81, -3.175) if side == "right" else (-3.81, -3.175)
    vo = (3.81, 3.175) if side == "right" else (-3.81, 3.175)
    return place("R", ref, val, x, y, 0, {"BaseID": base, "Status": status, "Note": note_},
                 ref_off=ro, val_off=vo, justify="left" if side == "right" else "right")


