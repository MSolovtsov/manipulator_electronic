#!/usr/bin/env python3
"""Генератор схемы платы LR (режим ЛР) манипулятора для лабораторных работ — формат KiCad 10.

Создаёт boards/LR/LR.kicad_sch (+ .kicad_pro и таблицы библиотек, если их нет) и обновляет общую библиотеку
символов lib/symbols/manipulator.kicad_sym. Общие помощники — scripts/sch_common.py.

Состав (по bom/Component_Base.xlsx, Размещение = LR, и docs/board-partition.md):
  X1…X4 — разъёмы к платам CH1…CH4 (по 5 цепей: IN1, IN2, SDA, SCL, GND_L — ответная часть X2 платы CH);
  X5…X8 — разъёмы к панели ЛР (E-098), по 5 цепей на группу M1…M4; тип органов подключения на самой
    панели (клемма, гнездо) требует уточнения: позиция клемм ZP-001 исключена из базы 06.10.2026;
  R1…R8 — последовательные 100 Ом (E-052) в линиях SDA и SCL каждой группы, со стороны клемм;
  VD3, VD4 … — сборки BAT54S (E-053) ограничивают SDA и SCL каждой группы на 3,3 В и GND_L;
  VD1, VD2 … — диоды 1N4148 (E-054) встречно в линиях IN1, IN2 каждой группы (катод к линии, анод на GND_L);
  X9 — разъём к плате MC (ответная часть X10 MC: 3V3, SCL, SDA, GND_L, шина I2C до мультиплексора);
  DD1 — расширитель портов PCF8574 (E-060), адрес A0…A2 на GND_L (0x20);
  HL1…HL4 — двухцветные светодиоды состояния звеньев (E-061) с резисторами R9…R16 150 Ом (E-062),
    общий анод на 3,3 В, катоды на выходы P0…P7 (зажигание нулём).
Разъёмы и группы клемм — таблицами «Контакт | Цепь» (ГОСТ 2.702, стиль курсового проекта кафедры).

Лист A2 (594 × 420), а не A3: четыре одинаковые группы защиты по пять линий каждая на A3 не размещаются
без пересечений и без захода в зону основной надписи.

Порядок защиты принят классический: клемма → последовательный резистор 100 Ом → ограничитель BAT54S →
разъём к плате CH. Резистор ограничивает ток через диоды сборки, ограничитель стоит со стороны платы CH.

Минимум стрелок (CLAUDE.md): линиями идут все пять цепей каждой группы от разъёма CH до клемм, шина I2C
от X9 к DD1, катоды светодиодов к выходам PCF8574 и аноды к магистрали 3,3 В. Стрелки-порты — только для
3V3 и GND_L у ограничителей и диодов (по два вывода у каждого, линию туда не провести без пересечения
сигнальных дорожек полосы) и для питания разъёмов.

Запуск: python3 scripts/gen_LR_sch.py (из каталога scripts или корня репозитория); затем scripts/check_sch.py
"""
