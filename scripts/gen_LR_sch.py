sys.path.insert(0, str(Path(__file__).resolve().parent))
import doc_titles as dt                 # noqa: E402  наименования и обозначения
import sch_common as sc                    # noqa: E402
from sch_common import *                   # noqa: E402,F401,F403

sc.PROJECT = PROJECT = "LR"
sc.ROOT_UUID = ROOT_UUID = "7b2e4d19-6c85-4a37-b0e2-1f6a8c35d947"
sc.OX = 30.48        # таблицы разъёмов выросли до 38,1 мм — весь лист сдвинут правее левого поля рамки
sc.FOOTPRINTS.clear()
sc.FOOTPRINTS.update({                     # имена — те же, что будут в scripts/gen_LR_pcb.py (PLACE)
    **{f"X{k}": "manipulator:JST_XH_B5B-XH-A_L" for k in range(1, 5)},
    **{f"X{k}": "manipulator:JST_XH_B5B-XH-A_L" for k in range(5, 9)},       # как X1…X4 (решение Mikhail 05.10.2026)
    "X9": "manipulator:JST_XH_B4B-XH-A_R", "DD1": "manipulator:DIP-16_W7.62mm",
    **{f"R{i}": "manipulator:R_Axial_P10.16mm_V" for i in range(1, 17)},
    **{f"VD{i}": ("manipulator:D_DO-35_P7.62mm" if i % 4 in (1, 2) else "manipulator:SOT-23") for i in range(1, 17)},
    **{f"HL{k}": "manipulator:LED_Bicolor_5mm" for k in range(1, 5)},
})


def stub(p, dx, dy, net):
    return to_pwr(p, net, dx, dy, down=dy > 0)


def R(ref, val, x, y, base, status, note_, side="right"):
    ro = (3.81, -3.175) if side == "right" else (-3.81, -3.175)
    vo = (3.81, 3.175) if side == "right" else (-3.81, 3.175)
    return place("R", ref, val, x, y, 0, {"BaseID": base, "Status": status, "Note": note_},
                 ref_off=ro, val_off=vo, justify="left" if side == "right" else "right")


# ======================================================================================================
# Четыре одинаковые группы M1…M4: разъём к CH → защита → разъём к панели
# ======================================================================================================
XCH, XT = 40.64, 330.2                     # выводы таблиц: разъём к CH (справа), разъём к панели (слева)
BAND = [25.4, 101.6, 177.8, 254.0]         # верх полосы каждой группы (шаг 76,2 под строку таблицы 5,08 мм)
LANE = {"IN1": 0.0, "IN2": 15.24, "SDA": 35.56, "SCL": 50.8, "GND_L": 66.04}    # горизонтали внутри полосы
ROW = {"IN1": 0.0, "IN2": 2.54, "SDA": 5.08, "SCL": 7.62, "GND_L": 10.16}       # строки таблиц
FANOUT = {"GND_L": 44.45, "SCL": 46.99, "SDA": 49.53, "IN2": 52.07}             # вертикали разбега (глубже — левее)
FANIN = {"IN2": 238.76, "SDA": 259.08, "SCL": 279.4, "GND_L": 299.72, "IN1": 320.04}   # шаг 20,32 под подписи резисторов
R_IN = {"SDA": 26.67, "SCL": 36.83}        # центр последовательного резистора внутри вертикали сбора

for k in range(4):
    Y0 = BAND[k]
    m = k + 1
    nets = [f"M{m}_IN1", f"M{m}_IN2", f"M{m}_SDA", f"M{m}_SCL", "GND_L"]
    XC = table(f"X{m}", nets, XCH, Y0, "right", "E-098",
               f"К плате CH{m} (ответная часть X2 CH): 1 IN1, 2 IN2, 3 SDA, 4 SCL, 5 GND_L", "B5B-XH-A")
    XTB = table(f"X{5 + k}", nets, XT, r2(Y0 + 8.89), "left", "E-098",
                f"К панели ЛР, группа M{m}: 1 IN1, 2 IN2, 3 SDA, 4 SCL, 5 GND_L",
                "B5B-XH-A")
    # --- разбег: из строк таблицы на свои горизонтали
    for sig in ("GND_L", "SCL", "SDA", "IN2"):
        p = XC[str(list(ROW).index(sig) + 1)]
        xf = FANOUT[sig]
        path(p, (xf, p[1]), (xf, r2(Y0 + LANE[sig])))
    # --- защита IN1, IN2: диод 1N4148 катодом к линии, анодом на GND_L (в промежутке под своей горизонталью)
    for i, sig in enumerate(("IN1", "IN2")):
        yl = r2(Y0 + LANE[sig])
        yd = r2(yl + 7.62)
        VD = place("D", f"VD{4 * k + i + 1}", "1N4148", 92.71, yd, 0,
                   {"BaseID": "E-054", "Status": "Утверждено",
                    "Note": f"Встречный диод линии {sig} группы M{m}: ограничивает отрицательное напряжение со стороны панели"},
                   ref_off=(0, -3.81), val_off=(0, 3.81), justify=None)
        path((80.01, yl), (80.01, yd), VD["1"])
        junction(80.01, yl)
        wire(VD["2"], (102.87, yd)); port("GND_L", 102.87, yd, wire_dir=-1, incoming=True)
    # --- защита SDA, SCL: сборка BAT54S между 3,3 В и GND_L
    for i, sig in enumerate(("SDA", "SCL")):
        yl = r2(Y0 + LANE[sig])
        yc = r2(yl + 7.62)
        VD = place("D_BAT54S", f"VD{4 * k + i + 3}", "BAT54S", 142.24, yc, 0,
                   {"BaseID": "E-053", "Status": "Утверждено",
                    "Note": f"Ограничитель линии {sig} группы M{m} на 3,3 В и GND_L"},
                   ref_off=(-12.7, -5.08), val_off=(-12.7, 0), justify="right")
        wire((132.08, yl), VD["3"])
        junction(132.08, yl)
        wire(VD["2"], (157.48, VD["2"][1])); port("3V3", 157.48, VD["2"][1], wire_dir=-1, incoming=True)
        wire(VD["1"], (157.48, VD["1"][1])); port("GND_L", 157.48, VD["1"][1], wire_dir=-1, incoming=True)
    # --- горизонтали и сбор к клеммам; в вертикалях SDA и SCL стоят последовательные резисторы 100 Ом
    for sig in ("IN1", "IN2", "SDA", "SCL", "GND_L"):
        yl = r2(Y0 + LANE[sig])
        xf = FANIN[sig]
        x_from = XCH if sig == "IN1" else FANOUT[sig]
        taps = [80.01] if sig in ("IN1", "IN2") else ([132.08] if sig in ("SDA", "SCL") else [200.66])
        hline(yl, taps, x_from, xf)
        if sig == "GND_L":                      # землю группы привязать к общей GND_L платы
            stub((200.66, yl), 0, 5.08, "GND_L")
        t = XTB[str(list(ROW).index(sig) + 1)]
        if sig in R_IN:
            Rr = R(f"R{2 * k + (1 if sig == 'SDA' else 2)}", "100 Ом", xf, r2(Y0 + R_IN[sig]), "E-052", "Утверждено",
                   f"Последовательная защита линии {sig} группы M{m} со стороны панели",
                   side="left" if sig == "SDA" else "right")
            wire((xf, yl), Rr["2"])
            if abs(Rr["1"][1] - t[1]) > 0.01:
                wire(Rr["1"], (xf, t[1]))
            wire((xf, t[1]), t)
        else:
            path((xf, yl), (xf, t[1]), t)

# ======================================================================================================
# Индикация: разъём к MC (X9), расширитель портов DD1 (PCF8574), светодиоды HL1…HL4 с резисторами R9…R16
# ======================================================================================================
X9 = table("X9", ["3V3", "SCL", "SDA", "GND_L"], 431.8, 30.48, "right", "E-092",
           "К плате MC (ответная часть X10 MC, шина I2C до мультиплексора): 1 3V3, 2 SCL, 3 SDA, 4 GND_L",
           "B4B-XH-A")
tport(X9, "1", "3V3", False); tport(X9, "4", "GND_L", False)
tport(X9, "2", "SCL", False); tport(X9, "3", "SDA", False)   # шину I2C линией к DD1 не провести: выводы SCL/SDA
# расширителя обращены вправо, а обе линии идут слева — любой обход даёт пересечение

DD1 = place("IC_PCF8574", "DD1", "PCF8574", 505.46, 149.86, 0,
           {"BaseID": "E-060", "Status": "Утверждено",
            "Note": "Расширитель портов индикации, адрес 0x20 (A0…A2 на GND_L); выходы зажигают светодиоды нулём"},
           ref_off=(-12.7, -33.02), val_off=(-12.7, -27.94), justify="right")
# шина I2C приходит стрелками-портами (см. примечание 4)
wire(DD1["14"], (523.24, DD1["14"][1])); port("SCL", 523.24, DD1["14"][1], wire_dir=-1, incoming=True)
wire(DD1["15"], (523.24, DD1["15"][1])); port("SDA", 523.24, DD1["15"][1], wire_dir=-1, incoming=True)
stub(DD1["16"], 7.62, -7.62, "3V3")
nc(*DD1["13"])
for n in ("1", "2", "3", "8"):                                                 # A0…A2 и VSS — на GND_L
    wire(DD1[n], (541.02, DD1[n][1]))
vline(541.02, [DD1["2"][1], DD1["3"][1], DD1["8"][1]], DD1["1"][1], r2(DD1["8"][1] + 5.08))
gnd_dn("GND_L", 541.02, r2(DD1["8"][1] + 5.08))

X_LED, Y_LED0, LED_STEP = 424.18, 69.85, 50.8
X_RA, X_RB = 416.56, 431.8                                                     # резисторы катодов: левый и правый
X_A = 381.0                                                                    # магистраль 3,3 В к анодам
anodes = []
src = []
for k in range(4):
    cy = r2(Y_LED0 + k * LED_STEP)
    HL = place("LED_Bicolor_CA", f"HL{k + 1}", "зел/красн", X_LED, cy, 0,
               {"BaseID": "E-061", "Status": "Утверждено",
                "Note": f"Состояние звена M{k + 1}: зелёный — норма, красный — авария (цоколёвку сверить)"},
               ref_off=(10.16, -5.08), val_off=(10.16, 0), justify="left")
    wire(HL["1"], (X_A, HL["1"][1])); anodes.append(HL["1"][1])
    Rb = R(f"R{10 + 2 * k}", "150 Ом", X_RB, r2(cy + 17.78), "E-062", "Утверждено",
           f"Ток красного светодиода HL{k + 1}")
    Ra = R(f"R{9 + 2 * k}", "150 Ом", X_RA, r2(cy + 22.86), "E-062", "Утверждено",
           f"Ток зелёного светодиода HL{k + 1}", side="left")
    path(HL["3"], (X_RB, HL["3"][1]))                                          # правый катод — прямо на R
    path(HL["2"], (X_RA, HL["2"][1]), Ra["1"])                                 # левый катод — отводом вниз
    src += [Rb["2"], Ra["2"]]
vline(X_A, anodes[1:-1], anodes[0], anodes[-1])
rail_up("3V3", X_A, r2(anodes[0] - 5.08))
wire((X_A, r2(anodes[0] - 5.08)), (X_A, anodes[0]))
junction(X_A, anodes[0])

# --- пучок: выходы R9…R16 → выводы P0…P7 (вложенные Г-линии без пересечений)
P_PINS = ["4", "5", "6", "7", "9", "10", "11", "12"]   # P0 — красный HL1, P1 — зелёный HL1, далее по парам
LANE_X = [459.74, 463.55, 467.36, 471.17, 474.98, 478.79, 482.6, 486.41]
down = [(i, s) for i, s in enumerate(src) if s[1] < DD1[P_PINS[i]][1]]
up = [(i, s) for i, s in enumerate(src) if s[1] > DD1[P_PINS[i]][1]]
for j, (i, s) in enumerate(reversed(down)):                 # идущие вниз: глубже цель — раньше поворот
    xf = LANE_X[j]
    t = DD1[P_PINS[i]]
    path(s, (xf, s[1]), (xf, t[1]), t)
for j, (i, s) in enumerate(up):                             # идущие вверх: глубже источник — позже поворот
    xf = LANE_X[len(down) + j]
    t = DD1[P_PINS[i]]
    path(s, (xf, s[1]), (xf, t[1]), t)

