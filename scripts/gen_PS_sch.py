    "5. Подсветка кнопки питания E-002 — встроенный индикатор 24 В, резистора нет: X2 (3, 4). Кнопка E-002 — с фиксацией",
    "   (самоподхвата K1 нет). Индикатор кнопки KH (E-024, 5 В) питается от шины KH на плате MC (X3 MC) — индикация режима ЛР.",
