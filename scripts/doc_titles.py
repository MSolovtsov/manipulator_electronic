#!/usr/bin/env python3
"""Единая таблица обозначений и наименований документов проекта.

Правила оформления основной надписи (организация, группа, подписи, структура
обозначения, аббревиатуры видов документов) — корневой CLAUDE.md, раздел
«Основная надпись — постоянные значения проекта». Номера плат внутри блока
электроники — electronics/CLAUDE.md, раздел «Обозначения документов».

Менять наименование, номер или подпись **только здесь**: генераторы схем и плат
берут строки отсюда, поэтому смена формулировки — правка одной таблицы,
а не одиннадцати файлов.
"""

PROJECT = "Манипулятор для лабораторных работ"
PREFIX = "СМ7"                   # постоянная документационная составляющая
BLOCK = "02"                     # блок электроники
ORG = "МГТУ им. Н.Э. Баумана"
GROUP = "СМ7-21М"                # ПЕРЕД КАЖДЫМ ВЫПУСКОМ документов спрашивать группу у Mikhail
DEV = "Соловцов М. А."           # Разраб.
CHK = "Бошляков А. А."           # Пров.

BOARDS = {                       # код: (номер изделия в обозначении, наименование изделия)
    "PS": ("01", "Плата питания"),
    "MC": ("02", "Плата микроконтроллера"),
    "CH": ("03", "Плата силовой части"),
    "LR": ("04", "Плата режима ЛР"),
    "GR": ("05", None),          # наименование требует уточнения
}

DOCS = {                         # аббревиатура: (группа ДД в обозначении, полное наименование)
    "ПЭ3": ("00", "Перечень элементов"),
    "Э3": ("00", "Схема электрическая принципиальная"),
    "СБ": ("00", "Сборочный чертёж"),
    "ПП": ("01", "Плата печатная"),                        # деталь 01 — без аббревиатуры в обозначении
    "Э2": ("00", "Схема электрическая функциональная"),   # общеблочный документ, изделие 00
}

NO_ABBR = {"ПП"}                 # чертёж печатной платы — документ детали, шифр вида документа не пишется


def board_name(code):
    name = BOARDS[code][1]
    if name is None:
        raise ValueError(f"наименование платы {code} требует уточнения — внести в doc_titles.BOARDS")
    return name


def item(code):
    """Наименование изделия для верхней строки графы наименования."""
    return f"{PROJECT}. {board_name(code)}"


def doc_name(doc):
    """Наименование документа полностью — нижняя строка графы наименования."""
    return DOCS[doc][1]


def designation(code, doc):
    """Обозначение документа с аббревиатурой: СМ7.02.01.00.00 Э3. code=None — общеблочный документ."""
    board = "00" if code is None else BOARDS[code][0]
    base = f"{PREFIX}.{BLOCK}.{board}.{DOCS[doc][0]}.00"
    return base if doc in NO_ABBR else f"{base} {doc}"


def company():
    return f"{ORG}, группа {GROUP}"


def kicad_title(code, doc):
    """Одной строкой для внутренней надписи KiCad; лист ЕСКД собирает генератор PDF."""
    return f"{item(code)}. {doc_name(doc)}"


def title_block(code, doc, rev):
    """Словарь для sch_common.write_project()."""
    return {"title": kicad_title(code, doc), "rev": rev, "company": company(),
            "comment1": designation(code, doc), "comment2": DEV, "comment6": CHK}


def silk(code, rev):
    """Короткая надпись на шелкографии платы: места мало, проект не пишем."""
    return f"{board_name(code)} {code} rev {rev}"
